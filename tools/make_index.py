#!/usr/bin/env python3
"""Write docs/preview/INDEX.md plus one enlarged image per species per growth stage.

    python3 tools/make_index.py      (run tools/make_textures.py first)

Images go to docs/preview/stages/<species>/<NN>_<stage>.png (12x, nearest-neighbour,
on a checkerboard so transparency is visible). These are renders of the textures,
not in-game screenshots.
"""
import sys
from pathlib import Path

import yaml
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SCALE = 12
SIZE = 16


def enlarge(src: Path) -> Image.Image:
    im = Image.open(src).convert("RGBA")
    n = im.width                                          # 16 or 32 px textures, enlarged to the same size
    z = SIZE * SCALE // n
    bg = Image.new("RGBA", (n * z, n * z))
    d = ImageDraw.Draw(bg)
    for y in range(n):
        for x in range(n):
            c = (88, 96, 108, 255) if (x + y) % 2 else (72, 80, 92, 255)
            d.rectangle([x * z, y * z, (x + 1) * z - 1, (y + 1) * z - 1], fill=c)
    bg.alpha_composite(im.resize((n * z, n * z), Image.NEAREST))
    return bg


def main() -> int:
    out_dir = ROOT / "docs" / "preview"
    lines = ["# Plant stage previews", "",
             "Enlarged renders (12x) of every growth-stage texture. Generated by `tools/make_index.py` from `plants/*.yaml`; "
             "these are renders of the 16x16 textures, not in-game screenshots.", "",
             "Contact sheet of everything: [all.png](all.png)", ""]
    total = 0
    for f in sorted((ROOT / "plants").glob("*.yaml")):
        d = yaml.safe_load(f.read_text(encoding="utf-8"))
        pid = d["id"]
        lines += [f"## {d['names']['scientific']} - {d['names']['in_game']}", "",
                  f"Confidence: **{d.get('confidence', '?')}**. Implementation type: `{d['implementation']['type']}`.", "",
                  "| # | Stage | Image | What it shows |", "|---|---|---|---|"]
        for i, st in enumerate(d["growth_stages"], 1):
            rel = f"stages/{pid}/{i:02d}_{st['id']}.png"
            dest = out_dir / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            enlarge(ROOT / st["texture"]).save(dest)
            desc = st["description"].replace("|", "/")
            lines.append(f"| {i} | {st['name']} | ![{pid} {st['id']}]({rel}) | {desc} |")
            total += 1
        lines.append("")
        segs = d.get("segment_textures", [])
        if segs:
            lines += ["Extra blocks for plants taller than 1 block at the configured scale:", "",
                      "| Role | Image | Note |", "|---|---|---|"]
            for sg in segs:
                rel = f"stages/{pid}/segment_{sg['role']}.png"
                enlarge(ROOT / sg["texture"]).save(out_dir / rel)
                lines.append(f"| {sg['role']} | ![{pid} {sg['role']}]({rel}) | {sg['note']} |")
                total += 1
            lines.append("")
            lower = [sg for sg in segs if sg["role"] == "lower"]
            if lower:
                low = Image.open(ROOT / lower[0]["texture"]).convert("RGBA")
                tops = [st for st in d["growth_stages"] if st["id"] in ("vegetative", "budding", "flowering", "fruiting", "ripe_capsule")]
                stack = Image.new("RGBA", (len(tops) * (SIZE * SCALE + 8) + 8, 2 * SIZE * SCALE + 16), (46, 52, 60, 255))
                for i, st in enumerate(tops):
                    top = enlarge(ROOT / st["texture"])
                    bot = enlarge(ROOT / lower[0]["texture"])
                    x = 8 + i * (SIZE * SCALE + 8)
                    stack.paste(top, (x, 8))
                    stack.paste(bot, (x, 8 + SIZE * SCALE))
                rel = f"stages/{pid}/stack_2_blocks.png"
                stack.save(out_dir / rel)
                lines += [f"Full-height plant (2 blocks): vegetative, budding, flowering, fruiting, ripe capsule, each over the lower block.", "",
                          f"![{pid} 2-block stack]({rel})", ""]
    (out_dir / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {total} stage images and INDEX.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
